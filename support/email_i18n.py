def get_survey_label(value, lang):
    if not value:
        return '—'
    d = SURVEY_VALUE_LABELS.get(value, {})
    return d.get(lang, d.get('fa', value))


def get_cabin_time_of_day(value, lang):
    if not value:
        return '—'
    d = CABIN_TIME_OF_DAY.get(value, {})
    return d.get(lang, d.get('fa', value))


def get_labels(lang, form_type):
    """Return labels dict for given language and form type."""
    lang = lang or 'fa'
    if lang not in ('fa', 'en', 'ar'):
        lang = 'fa'
    if form_type == 'complaint':
        return COMPLAINT_LABELS.get(lang, COMPLAINT_LABELS['fa'])
    if form_type == 'survey':
        return SURVEY_LABELS.get(lang, SURVEY_LABELS['fa'])
    if form_type == 'cabin':
        return CABIN_SAFETY_LABELS.get(lang, CABIN_SAFETY_LABELS['fa'])
    if form_type == 'safety_hazard':
        return SAFETY_HAZARD_LABELS.get(lang, SAFETY_HAZARD_LABELS['fa'])
    return {}
