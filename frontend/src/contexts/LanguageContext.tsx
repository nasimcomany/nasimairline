interface LanguageProviderProps {
  children: ReactNode;
}

export const LanguageProvider: React.FC<LanguageProviderProps> = ({ children }) => {
  const [language, setLanguage] = useState<Language>(() => {
    // Load from localStorage if available
    const saved = localStorage.getItem('language') as Language;
    return saved && ['fa', 'ar', 'en'].includes(saved) ? saved : 'fa';
  });

  // Get direction and font class based on language
  const direction = language === 'en' ? 'ltr' : 'rtl';
  const fontClass = language === 'en' 
    ? 'english-font' 
    : language === 'ar' 
    ? 'arabic-font' 
    : 'persian-font-vazir';

  // Update document direction and body class when language changes
  useEffect(() => {
    document.documentElement.dir = direction;
    document.body.dir = direction;
    document.body.className = document.body.className
      .replace(/persian-font-vazir|arabic-font|english-font/g, '')
      .trim() + ' ' + fontClass;
    
    // Save to localStorage
    localStorage.setItem('language', language);
  }, [language, direction, fontClass]);

  const t = (key: string): string => {
    return translations[language][key as keyof typeof translations[typeof language]] || key;
  };

  const handleSetLanguage = (lang: Language) => {
    setLanguage(lang);
  };

  const value: LanguageContextType = {
    language,
    setLanguage: handleSetLanguage,
    t,
    direction,
    fontClass,
  };

  return (
    <LanguageContext.Provider value={value}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = (): LanguageContextType => {
  const context = useContext(LanguageContext);
  if (context === undefined) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
};
